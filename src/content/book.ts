import { childInteraction } from "./childInteractions.ts";
import type { Block, BookPage } from "./types.ts";
type WithoutId<T> = T extends unknown ? Omit<T, "id"> : never;
type BlockDraft = WithoutId<Block>;
const img = (p: number, name: string) =>
  `p${String(p).padStart(3, "0")}_${name}`;
const read = (
  title: string,
  body: string,
  images: string[] = [],
): BlockDraft => ({
  kind: "read",
  title,
  prompt: "Рассмотри страницу",
  body,
  images,
});
const number = (
  title: string,
  prompt: string,
  expected: number,
  images: string[] = [],
  sourceText?: string,
): BlockDraft => ({
  kind: "number",
  title,
  prompt,
  expected,
  images,
  sourceText,
  adaptation: !sourceText,
  hint: "Считай по одному. Не пропускай предметы и не считай один предмет дважды.",
});
const choice = (
  title: string,
  prompt: string,
  options: string[],
  expected: string,
  images: string[],
  sourceText?: string,
): BlockDraft => ({
  kind: "choice",
  title,
  prompt,
  options,
  expected,
  images,
  sourceText,
  adaptation: !sourceText,
  hint: "Внимательно рассмотри рисунок и сравни обе стороны.",
});
const counters = (
  title: string,
  prompt: string,
  expected: number | undefined,
  token: "stick" | "circle",
  images: string[],
  review?: string,
): BlockDraft => ({
  kind: "counters",
  title,
  prompt,
  sourceText: prompt,
  expected,
  token,
  images,
  review,
  hint: "Нажимай «Добавить», чтобы положить один предмет. Лишний можно убрать.",
});
const draw = (
  title: string,
  prompt: string,
  image: string,
  rubric: string,
  guide?: string,
): BlockDraft => ({
  kind: "draw",
  title,
  prompt,
  images: [image],
  rubric,
  guide,
  adaptation: true,
  hint: "Можно рисовать пальцем, мышью или стилусом. Не спеши: аккуратность приходит с практикой.",
});
const shape = (
  title: string,
  prompt: string,
  down: boolean,
  triangle: boolean,
  image: string,
): BlockDraft => ({
  kind: "shape",
  title,
  prompt,
  sourceText: triangle ? "Сложи из палочек:" : "Составь из палочек:",
  images: [image],
  vertices: down
    ? [
        { x: 0.15, y: 0.2 },
        { x: 0.85, y: 0.2 },
        { x: 0.5, y: 0.8 },
      ]
    : [
        { x: 0.15, y: 0.8 },
        { x: 0.5, y: 0.2 },
        { x: 0.85, y: 0.8 },
      ],
  edges: triangle
    ? [
        [0, 1],
        [1, 2],
        [0, 2],
      ]
    : down
      ? [
          [0, 2],
          [1, 2],
        ]
      : [
          [0, 1],
          [1, 2],
        ],
  hint: "Выбери две точки: между ними появится палочка. Нажми те же точки, чтобы убрать её.",
});
function page(
  n: number,
  title: string,
  subtitle: string,
  hero: string,
  blocks: BlockDraft[],
): BookPage {
  return {
    id: `p${String(n).padStart(3, "0")}`,
    number: n,
    title,
    subtitle,
    hero,
    sourceDoc: `textbook/page_docs/arithmetic_grade1_pchelko_1959_p${String(n).padStart(3, "0")}.md`,
    blocks: blocks.map((b, i) =>
      childInteraction({
        ...b,
        id: `p${String(n).padStart(3, "0")}-block${String(i + 1).padStart(2, "0")}`,
      } as Block),
    ),
  };
}
