/**
 * Spoken forms for the narrator. Screen text stays as printed («2 + 1 = 3»,
 * «5 см», «4 + □ = 6»); the voice gets words with the right gender and case
 * («два плюс один равно три», «пять сантиметров», «четыре плюс сколько равно шесть»).
 * Covers 0–999: the course counts to 100, page numbers go to 144.
 */
export type Gender = "m" | "f" | "n";
const ONES: Record<Gender, string[]> = {
  m: [
    "ноль",
    "один",
    "два",
    "три",
    "четыре",
    "пять",
    "шесть",
    "семь",
    "восемь",
    "девять",
  ],
  f: [
    "ноль",
    "одна",
    "две",
    "три",
    "четыре",
    "пять",
    "шесть",
    "семь",
    "восемь",
    "девять",
  ],
  n: [
    "ноль",
    "одно",
    "два",
    "три",
    "четыре",
    "пять",
    "шесть",
    "семь",
    "восемь",
    "девять",
  ],
};
const TEENS = [
  "десять",
  "одиннадцать",
  "двенадцать",
  "тринадцать",
  "четырнадцать",
  "пятнадцать",
  "шестнадцать",
  "семнадцать",
  "восемнадцать",
  "девятнадцать",
];
const TENS = [
  "",
  "",
  "двадцать",
  "тридцать",
  "сорок",
  "пятьдесят",
  "шестьдесят",
  "семьдесят",
  "восемьдесят",
  "девяносто",
];
const HUNDREDS = [
  "",
  "сто",
  "двести",
  "триста",
  "четыреста",
  "пятьсот",
  "шестьсот",
  "семьсот",
  "восемьсот",
  "девятьсот",
];
export function numberToWords(n: number, gender: Gender = "m"): string {
  if (!Number.isInteger(n) || n < 0 || n > 999) return String(n);
  if (n < 10) return ONES[gender][n];
  if (n < 20) return TEENS[n - 10];
  const parts: string[] = [];
  const h = Math.floor(n / 100),
    t = Math.floor((n % 100) / 10),
    o = n % 10;
  if (h) parts.push(HUNDREDS[h]);
  if (n % 100 >= 10 && n % 100 < 20) parts.push(TEENS[(n % 100) - 10]);
  else {
    if (t) parts.push(TENS[t]);
    if (o) parts.push(ONES[gender][o]);
  }
  return parts.join(" ");
}
/** «пять сантиметров», «два сантиметра», «один сантиметр». */
export function plural(
  n: number,
  one: string,
  few: string,
  many: string,
): string {
  const m10 = n % 10,
    m100 = n % 100;
  if (m100 >= 11 && m100 <= 14) return many;
  if (m10 === 1) return one;
  if (m10 >= 2 && m10 <= 4) return few;
  return many;
}
const UNITS: Record<string, [Gender, string, string, string]> = {
  см: ["m", "сантиметр", "сантиметра", "сантиметров"],
  м: ["m", "метр", "метра", "метров"],
  дм: ["m", "дециметр", "дециметра", "дециметров"],
  кг: ["m", "килограмм", "килограмма", "килограммов"],
  л: ["m", "литр", "литра", "литров"],
  "руб.": ["m", "рубль", "рубля", "рублей"],
  руб: ["m", "рубль", "рубля", "рублей"],
  р: ["m", "рубль", "рубля", "рублей"],
  "коп.": ["f", "копейка", "копейки", "копеек"],
  коп: ["f", "копейка", "копейки", "копеек"],
  к: ["f", "копейка", "копейки", "копеек"],
};
/** Nouns the book counts in the feminine or neuter, by stem; anything else reads as masculine.
 * An ending heuristic would misfire on genitive forms («2 мальчика»), so only the dictionary decides. */
const FEMININE =
  /^(лыж|книг|книж|ягод|девочк|птичк|птиц|рыбк|рыб|тетрад|палочк|карточк|монет|копейк|клетк|точк|чёрточк|черточк|лини|полоск|коробк|корзин|тарелк|чашк|ложк|вилк|кукл|машин|груш|слив|вишн|морков|свёкл|свекл|реп|лодк|лошад|коров|коз|овц|куриц|утк|бабочк|звёздочк|звездочк|ёлочк|елочк|шапк|лент|кружк(?!ов|а$|и$)|конфет|марк|пуговиц|бус|ветк|ветв|стран|недел|минут|секунд|задач|фигур|част|половин|четверт|сторон|мерк|гирьк|гир|банк|бутылк|кучк|стопк|пар|дюжин|полк|пачк|булк|лампочк|ёлк|елк|сосн|берёз|берез|рощ|скамейк|парт|доск|комнат|стен|двер|карандашниц|ручк|линейк|кисточк|краск|роз|астр|гвоздик|яблон|груш|морковк|редиск|капуст|тыкв|дын|картофелин|котлет|булочк|баранк|сушк|плюшк|чашк|кастрюл|сковород|миск|ваз|салфетк|тряпк|щётк|щетк|метл|лопат|грабл|пил|иголк|ниток|нитк|катушк|шишк|веточк|травинк|снежинк|капл|луж|тучк|звезд|луна|ночь|зим|весн|осен|сумк|варежк|рукавичк|шуб|юбк|кофт|рубашк|косынк|тесьм|полос|кноп|ступеньк|лесенк|дорожк|тропинк|ям|горк|речк|рек|волн|снежк|игрушк|пирамидк|погремушк|дудочк|скрипк|барабан(?!)|галк|ворон|сорок|синиц|ласточк|кошк|собак|мышк|белк|лис|обезьян|зебр|черепах|лягушк|улитк|стрекоз|пчел|пчёл|ос|мух|букашк|гусениц|шапочк|коляск|телег|тачк|санк|лыжн|команд|груп|стай|пар)/i;
const NEUTER =
  /^(яблок|яйц|яич|колёс|колес|ведр|ведёр|ведер|дерев|окн|окош|блюдц|зерн|зёрн|пер(о|ь)|крыл|мест|числ|слов|действ|колечк|облак|озер|озёр|пол(е|я)$|сел|гнезд|гнёзд|стекл|стёкл|кольц|колец|бревн|брёвн|полотенц|одеял|платьи|плать|письм|пис(е|ь)м|ружь|руж(е|ь)|копь|весл|вёсл|мыл|масл|молок|яблочк|окошечк|пятн|пятен|зеркал|печень|варень)/i;
function genderFor(noun?: string): Gender {
  if (!noun) return "m";
  const w = noun.toLowerCase();
  if (NEUTER.test(w)) return "n";
  if (FEMININE.test(w)) return "f";
  return "m";
}
const OPERATORS: [RegExp, string][] = [
  [/\s*(?:\+)\s*/g, " плюс "],
  [/\s*(?:−|-|–)\s*(?=\d|□|\?)/g, " минус "],
  [/\s*(?:×|·|∙|\*)\s*/g, " умножить на "],
  [/\s*(?::|÷)\s*(?=\d|□)/g, " разделить на "],
  [/\s*=\s*/g, " равно "],
  [/\s*>\s*/g, " больше, чем "],
  [/\s*<\s*/g, " меньше, чем "],
];
/** Turn one line of printed text into what the narrator says. */
export function spokenForm(text: string): string {
  let s = text.replace(/□|\?(?=\s*=)|…(?=\s*=)/g, " сколько ");
  for (const [re, word] of OPERATORS) s = s.replace(re, word);
  // «5 см» → «пять сантиметров»; the unit decides gender and case.
  s = s.replace(
    /(\d+)\s*(см|дм|кг|руб\.|руб|коп\.|коп|м|л|р|к)(?![а-яё])/gi,
    (_, num, unit) => {
      const n = Number(num);
      const u = UNITS[unit.toLowerCase()];
      if (!u) return `${numberToWords(n)} ${unit}`;
      return `${numberToWords(n, u[0])} ${plural(n, u[1], u[2], u[3])}`;
    },
  );
  // A number before a noun takes the noun's gender: «одна девочка», «две лыжи», «два мальчика».
  s = s.replace(
    /(\d+)(\s+)([а-яё]+)/gi,
    (_, num, gap, noun) =>
      `${numberToWords(Number(num), genderFor(noun))}${gap}${noun}`,
  );
  s = s.replace(/\d+/g, (num) => numberToWords(Number(num)));
  return s
    .replace(/\s+/g, " ")
    .replace(/\s+([,.!?;:])/g, "$1")
    .trim();
}
