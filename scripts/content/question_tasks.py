def question(number, expected, wrong_a, wrong_b, *,
             label='Выбери вопрос, на который можно ответить по условию задачи.',
             id='question'):
    options = [expected, wrong_a, wrong_b]
    # Vary the correct option's position without changing stable answer text.
    offset = number % len(options)
    options = options[offset:] + options[:offset]
    return dict(id=id, label=label, options=options, expected=expected)


