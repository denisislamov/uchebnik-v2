def fields(*questions):
    return [dict(id=f'q{i + 1}', label=label, expected=str(answer))
            for i, (label, answer) in enumerate(questions)]


def step(id, instruction, counts, token='stick', mode='place', **options):
    return dict(id=id, instruction=instruction, mode=mode,
                token=token, counts=counts, **options)


def practical(steps, *questions):
    return dict(kind='practical', steps=steps, fields=fields(*questions))


